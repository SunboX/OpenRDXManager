test('adopts a claim abandoned by a killed recoverer without leaking lock state', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-killed-recoverer-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const testRuntimeRoot = join(temporaryDirectory, 'runtime')
    await createMinimalNativeProject(controlledRoot)
    await mkdir(testRuntimeRoot)
    const paths = getNativeServiceBuildPaths({ projectRoot: controlledRoot })
    await mkdir(dirname(paths.lockPath), { recursive: true })
    await writeFile(paths.lockPath, JSON.stringify({ version: 1, token: '00000000-0000-4000-8000-000000000005', pid: 2_147_483_647, createdAt: Date.now() - 60_000 }))

    const recoveryGate = join(temporaryDirectory, 'killed-recoverer-claim-published')
    const recoveryRelease = join(temporaryDirectory, 'killed-recoverer-never-released')
    const killedCargoStarted = join(temporaryDirectory, 'killed-recoverer-cargo-started')
    const killedCargoRelease = join(temporaryDirectory, 'killed-recoverer-cargo-release')
    const killedRecoverer = spawnBuildWorker({
        projectRoot: controlledRoot,
        testRuntimeRoot,
        mode: 'success',
        startedPath: killedCargoStarted,
        releasePath: killedCargoRelease,
        recoveryGatePath: recoveryGate,
        recoveryReleasePath: recoveryRelease
    })
    context.after(() => killedRecoverer.kill('SIGKILL'))
    await waitForMarker(recoveryGate)
    assert.equal(killedRecoverer.kill('SIGKILL'), true)
    assert.equal(await waitForExit(killedRecoverer), null)

    const successorStarted = join(temporaryDirectory, 'successor-cargo-started')
    const successorRelease = join(temporaryDirectory, 'successor-cargo-release')
    const successor = spawnBuildWorker({
        projectRoot: controlledRoot,
        testRuntimeRoot,
        mode: 'success',
        startedPath: successorStarted,
        releasePath: successorRelease,
        artifactContents: 'successor-runtime'
    })
    context.after(() => successor.kill('SIGKILL'))
    await waitForMarker(successorStarted)
    await writeFile(successorRelease, 'release')
    assert.equal(await waitForExit(successor), 0)

    await assert.rejects(access(killedCargoStarted))
    await assert.rejects(access(paths.lockPath))
    assert.equal(
        (await readdir(dirname(paths.lockPath))).some((name) => name.includes('openrdx-native-service-build')),
        false
    )
    assert.equal(await readFile(join(await realpath(testRuntimeRoot), runtimePlatformDirectory(), executableName()), 'utf8'), 'successor-runtime')
})

test('preserves a live lock published by an acquisition admitted just before a recovery claim', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-lock-claim-admission-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const testRuntimeRoot = join(temporaryDirectory, 'runtime')
    await createMinimalNativeProject(controlledRoot)
    await mkdir(testRuntimeRoot)
    const paths = getNativeServiceBuildPaths({ projectRoot: controlledRoot })
    await mkdir(dirname(paths.lockPath), { recursive: true })
    await writeFile(paths.lockPath, JSON.stringify({ version: 1, token: '00000000-0000-4000-8000-000000000008', pid: 2_147_483_647, createdAt: Date.now() - 60_000 }))

    const contenderBeforeCreate = join(temporaryDirectory, 'contender-before-lock-create')
    const contenderCreateRelease = join(temporaryDirectory, 'contender-create-release')
    const contenderAfterCreate = join(temporaryDirectory, 'contender-after-lock-create')
    const contenderAfterCreateRelease = join(temporaryDirectory, 'contender-after-create-release')
    const contenderStarted = join(temporaryDirectory, 'contender-cargo-started')
    const contenderCargoRelease = join(temporaryDirectory, 'contender-cargo-release')
    const recovererGate = join(temporaryDirectory, 'recoverer-before-stale-unlink')
    const recovererGateRelease = join(temporaryDirectory, 'recoverer-stale-unlink-release')
    const recovererStarted = join(temporaryDirectory, 'recoverer-cargo-started')
    const recovererCargoRelease = join(temporaryDirectory, 'recoverer-cargo-release')
    const criticalPath = join(temporaryDirectory, 'cargo-critical-section')
    const overlapPath = join(temporaryDirectory, 'cargo-critical-overlap')

    const contender = spawnBuildWorker({
        projectRoot: controlledRoot,
        testRuntimeRoot,
        mode: 'success',
        startedPath: contenderStarted,
        releasePath: contenderCargoRelease,
        artifactContents: 'admitted-contender-runtime',
        beforeLockCreateGatePath: contenderBeforeCreate,
        beforeLockCreateReleasePath: contenderCreateRelease,
        afterLockCreateGatePath: contenderAfterCreate,
        afterLockCreateReleasePath: contenderAfterCreateRelease,
        criticalPath,
        overlapPath
    })
    context.after(() => contender.kill('SIGKILL'))
    await waitForMarker(contenderBeforeCreate)

    const recoverer = spawnBuildWorker({
        projectRoot: controlledRoot,
        testRuntimeRoot,
        mode: 'success-or-lock-timeout',
        startedPath: recovererStarted,
        releasePath: recovererCargoRelease,
        artifactContents: 'recoverer-must-not-stage',
        lockTimeoutMs: 250,
        recoveryGatePath: recovererGate,
        recoveryReleasePath: recovererGateRelease,
        criticalPath,
        overlapPath
    })
    context.after(() => recoverer.kill('SIGKILL'))
    await waitForMarker(recovererGate)

    await unlink(paths.lockPath)
    await writeFile(contenderCreateRelease, 'release')
    await waitForMarker(contenderAfterCreate)
    await writeFile(recovererGateRelease, 'release')
    assert.equal(await waitForMarkerOrExit(recovererStarted, recoverer), 'exited')

    await writeFile(contenderAfterCreateRelease, 'release')
    await waitForMarker(contenderStarted)
    await writeFile(contenderCargoRelease, 'release')
    await writeFile(recovererCargoRelease, 'release')
    const [recovererExit, contenderExit] = await Promise.all([waitForExit(recoverer), waitForExit(contender)])

    assert.equal(recovererExit, 0)
    assert.equal(contenderExit, 0)
    await assert.rejects(access(overlapPath))
    await assert.rejects(access(paths.lockPath))
    assert.equal(
        (await readdir(dirname(paths.lockPath))).some((name) => name.includes('openrdx-native-service-build')),
        false
    )
    assert.equal(await readFile(join(await realpath(testRuntimeRoot), runtimePlatformDirectory(), executableName()), 'utf8'), 'admitted-contender-runtime')
})
