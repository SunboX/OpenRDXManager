import { buildNativeService, buildNativeServiceForTest, getNativeServiceBuildPaths } from '../scripts/build-native-service.mjs'
import { DEVICE_SERVICE_ARGUMENTS, resolveDeviceServiceExecutable } from '../src/main/device-service-client.mjs'

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Creates the smallest locked Cargo project accepted by the native build hook.
 * @param {string} root - Empty temporary project root.
 * @returns {Promise<void>} Resolves after writing the manifest, lockfile, and binary.
 */
async function createMinimalNativeProject(root) {
    const crateRoot = join(root, 'native', 'rdx-service')
    await mkdir(join(crateRoot, 'src', 'bin'), { recursive: true })
    await writeFile(join(crateRoot, 'Cargo.toml'), '[package]\nname = "rdx-service"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n\n[[bin]]\nname = "openrdx-hardware"\npath = "src/bin/openrdx-hardware.rs"\n')
    await writeFile(join(crateRoot, 'Cargo.lock'), '# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "rdx-service"\nversion = "0.1.0"\n')
    await writeFile(join(crateRoot, 'src', 'bin', 'openrdx-hardware.rs'), 'fn main() {}\n')
}

/**
 * Creates a portable directory link, using a junction where Windows requires it.
 * @param {string} target - Existing external directory.
 * @param {string} linkPath - Link path inside the controlled root.
 * @returns {Promise<void>} Resolves after creating the link.
 */
async function createDirectoryLink(target, linkPath) {
    await symlink(target, linkPath, process.platform === 'win32' ? 'junction' : 'dir')
}

/** @returns {string} Development runtime platform directory for this host. */
function runtimePlatformDirectory() {
    if (process.platform === 'darwin') return 'macos'
    if (process.platform === 'win32') return 'windows'
    return 'linux'
}

test('rejects a symlinked Cargo target ancestor without writing outside the controlled project', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-source-link-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const externalTarget = join(temporaryDirectory, 'external-target')
    const sentinelPath = join(externalTarget, 'sentinel.txt')
    await createMinimalNativeProject(controlledRoot)
    await mkdir(externalTarget)
    await writeFile(sentinelPath, 'unchanged-source-sentinel')
    await createDirectoryLink(externalTarget, join(controlledRoot, 'native', 'rdx-service', 'target'))

    await assert.rejects(buildNativeService({ projectRoot: controlledRoot }), /native-service-path-symlink/)
    assert.equal(await readFile(sentinelPath, 'utf8'), 'unchanged-source-sentinel')
    assert.deepEqual(await readdir(externalTarget), ['sentinel.txt'])
})

test('rejects a symlinked runtime ancestor without changing an external executable sentinel', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-destination-link-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const externalRuntime = join(temporaryDirectory, 'external-runtime')
    const executableName = process.platform === 'win32' ? 'openrdx-hardware.exe' : 'openrdx-hardware'
    const sentinelPath = join(externalRuntime, executableName)
    await createMinimalNativeProject(controlledRoot)
    await mkdir(join(controlledRoot, 'out', 'native'), { recursive: true })
    await mkdir(externalRuntime)
    await writeFile(sentinelPath, 'unchanged-runtime-sentinel')
    await createDirectoryLink(externalRuntime, join(controlledRoot, 'out', 'native', runtimePlatformDirectory()))

    await assert.rejects(buildNativeService({ projectRoot: controlledRoot }), /native-service-path-symlink/)
    assert.equal(await readFile(sentinelPath, 'utf8'), 'unchanged-runtime-sentinel')
    assert.deepEqual(await readdir(externalRuntime), [executableName])
})

test('accepts only an explicit controlled test runtime root instead of an arbitrary destination path', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-test-root-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const testRuntimeRoot = join(temporaryDirectory, 'test-runtime')
    const arbitraryRuntimePath = join(temporaryDirectory, 'arbitrary', process.platform === 'win32' ? 'openrdx-hardware.exe' : 'openrdx-hardware')
    await createMinimalNativeProject(controlledRoot)
    await mkdir(testRuntimeRoot)

    await assert.rejects(buildNativeService({ projectRoot: '.', testRuntimeRoot }), /native-service-project-root-invalid/)
    await assert.rejects(buildNativeService({ projectRoot: controlledRoot, runtimePath: arbitraryRuntimePath }), /native-service-runtime-path-invalid/)
    const result = await buildNativeService({ projectRoot: controlledRoot, testRuntimeRoot })

    assert.equal(result.runtimePath, join(await realpath(testRuntimeRoot), runtimePlatformDirectory(), process.platform === 'win32' ? 'openrdx-hardware.exe' : 'openrdx-hardware'))
})

test('stages Cargo reported executable independently from ambient target overrides', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-build-'))
    // Windows executable sections/antivirus scans may outlive child exit very
    // briefly. Retry cleanup of this exact disposable root, never a real build.
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true, maxRetries: 5, retryDelay: 100 }))
    const ambientTargetDirectory = join(temporaryDirectory, 'ambient-target')
    const testRuntimeRoot = join(temporaryDirectory, 'runtime')
    await mkdir(testRuntimeRoot)

    const result = await buildNativeService({
        environment: { ...process.env, CARGO_TARGET_DIR: ambientTargetDirectory },
        projectRoot,
        testRuntimeRoot
    })

    assert.equal(relative(result.targetDirectory, result.artifactPath).startsWith('..'), false)
    await access(result.runtimePath, process.platform === 'win32' ? constants.F_OK : constants.X_OK)
    await assert.rejects(access(join(ambientTargetDirectory, 'debug', process.platform === 'win32' ? 'openrdx-hardware.exe' : 'openrdx-hardware')))
    const execution = spawnSync(result.runtimePath, DEVICE_SERVICE_ARGUMENTS, { encoding: 'utf8', input: '' })
    assert.equal(execution.status, 0)
    assert.equal(execution.stdout, '')
    assert.equal(execution.stderr, '')
})

test('preserves the last-known-good runtime executable when Cargo fails', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-stale-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const testRuntimeRoot = join(temporaryDirectory, 'runtime')
    await createMinimalNativeProject(controlledRoot)
    await writeFile(join(controlledRoot, 'native', 'rdx-service', 'src', 'bin', 'openrdx-hardware.rs'), 'this does not compile\n')
    await mkdir(join(testRuntimeRoot, runtimePlatformDirectory()), { recursive: true })
    const runtimePath = join(testRuntimeRoot, runtimePlatformDirectory(), process.platform === 'win32' ? 'openrdx-hardware.exe' : 'openrdx-hardware')
    await writeFile(runtimePath, 'last-known-good')

    await assert.rejects(buildNativeService({ projectRoot: controlledRoot, testRuntimeRoot }), /native-service-cargo-failed/)
    assert.equal(await readFile(runtimePath, 'utf8'), 'last-known-good')
})

test('revalidates exact build-lock ownership immediately before entering Cargo', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-pre-cargo-lock-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const testRuntimeRoot = join(temporaryDirectory, 'runtime')
    await createMinimalNativeProject(controlledRoot)
    await mkdir(join(testRuntimeRoot, runtimePlatformDirectory()), { recursive: true })
    const runtimePath = join(testRuntimeRoot, runtimePlatformDirectory(), process.platform === 'win32' ? 'openrdx-hardware.exe' : 'openrdx-hardware')
    await writeFile(runtimePath, 'pre-cargo-known-good')
    const paths = getNativeServiceBuildPaths({ projectRoot: controlledRoot })
    let ownershipRemoved = false
    let cargoEntered = false

    await assert.rejects(
        buildNativeServiceForTest(
            { projectRoot: controlledRoot, testRuntimeRoot },
            {
                onBeforeCargo: async () => {
                    ownershipRemoved = true
                    await unlink(paths.lockPath)
                    await writeFile(paths.lockPath, JSON.stringify({ version: 1, token: '00000000-0000-4000-8000-000000000004', pid: process.pid, createdAt: Date.now() }))
                },
                runCargo: async () => {
                    cargoEntered = true
                    throw new Error('cargo-must-not-run')
                }
            }
        ),
        /native-service-build-lock-invalid/
    )

    assert.equal(ownershipRemoved, true)
    assert.equal(cargoEntered, false)
    assert.equal(await readFile(runtimePath, 'utf8'), 'pre-cargo-known-good')
    assert.equal(JSON.parse(await readFile(paths.lockPath, 'utf8')).token, '00000000-0000-4000-8000-000000000004')
})

test('aborts before runtime rename when exact build-lock ownership is lost after staging copy', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-pre-rename-lock-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const testRuntimeRoot = join(temporaryDirectory, 'runtime')
    await createMinimalNativeProject(controlledRoot)
    await mkdir(join(testRuntimeRoot, runtimePlatformDirectory()), { recursive: true })
    const runtimePath = join(testRuntimeRoot, runtimePlatformDirectory(), process.platform === 'win32' ? 'openrdx-hardware.exe' : 'openrdx-hardware')
    await writeFile(runtimePath, 'last-known-good')
    const paths = getNativeServiceBuildPaths({ projectRoot: controlledRoot })
    let ownershipRemoved = false

    await assert.rejects(
        buildNativeServiceForTest(
            { projectRoot: controlledRoot, testRuntimeRoot },
            {
                onBeforeStageRename: async () => {
                    ownershipRemoved = true
                    await unlink(paths.lockPath)
                    await writeFile(paths.lockPath, JSON.stringify({ version: 1, token: '00000000-0000-4000-8000-000000000003', pid: process.pid, createdAt: Date.now() }))
                },
                runCargo: async ({ paths: controlledPaths }) => {
                    const artifactPath = join(controlledPaths.targetDirectory, 'debug', controlledPaths.executableName)
                    await mkdir(dirname(artifactPath), { recursive: true })
                    await writeFile(artifactPath, 'must-not-replace-runtime')
                    return { stdout: `${JSON.stringify({ reason: 'compiler-artifact', target: { name: 'openrdx-hardware', kind: ['bin'] }, profile: { test: false }, executable: artifactPath })}\n` }
                }
            }
        ),
        /native-service-build-lock-invalid/
    )

    assert.equal(ownershipRemoved, true)
    assert.equal(await readFile(runtimePath, 'utf8'), 'last-known-good')
    assert.equal(JSON.parse(await readFile(paths.lockPath, 'utf8')).token, '00000000-0000-4000-8000-000000000003')
    assert.equal(
        (await readdir(dirname(runtimePath))).some((name) => name.endsWith('.tmp')),
        false
    )
})

test('build and runtime share one deterministic development executable path', () => {
    const paths = getNativeServiceBuildPaths({ platform: process.platform, projectRoot })
    const runtimePath = resolveDeviceServiceExecutable({ appPath: projectRoot, resourcesPath: projectRoot, isPackaged: false, platform: process.platform })

    assert.equal(paths.runtimePath, runtimePath)
    assert.equal(getNativeServiceBuildPaths({ platform: 'darwin', projectRoot }).runtimePath, join(projectRoot, 'out', 'native', 'macos', 'openrdx-hardware'))
    assert.equal(getNativeServiceBuildPaths({ platform: 'linux', projectRoot }).runtimePath, join(projectRoot, 'out', 'native', 'linux', 'openrdx-hardware'))
    assert.equal(getNativeServiceBuildPaths({ platform: 'win32', projectRoot }).runtimePath, join(projectRoot, 'out', 'native', 'windows', 'openrdx-hardware.exe'))
})

test('accepts only an exact compile-time macOS manager signing team', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-team-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const controlledRoot = join(temporaryDirectory, 'project')
    const testRuntimeRoot = join(temporaryDirectory, 'runtime')
    await createMinimalNativeProject(controlledRoot)
    await mkdir(testRuntimeRoot)
    let observedTeam

    await buildNativeServiceForTest(
        { environment: { OPENRDX_MANAGER_TEAM_ID: '7UXAQ487HP' }, platform: 'darwin', projectRoot: controlledRoot, testRuntimeRoot },
        {
            runCargo: async ({ environment, paths }) => {
                observedTeam = environment.OPENRDX_MANAGER_TEAM_ID
                const artifactPath = join(paths.targetDirectory, 'debug', paths.executableName)
                await mkdir(dirname(artifactPath), { recursive: true })
                await writeFile(artifactPath, 'signed-team-fixture')
                return { stdout: `${JSON.stringify({ reason: 'compiler-artifact', target: { name: 'openrdx-hardware', kind: ['bin'] }, profile: { test: false }, executable: artifactPath })}\n` }
            }
        }
    )
    assert.equal(observedTeam, '7UXAQ487HP')

    for (const invalid of ['', 'lowercase1', 'SHORT', 'TOOLONG00001', 'BAD-TEAM01']) {
        await assert.rejects(buildNativeService({ environment: { OPENRDX_MANAGER_TEAM_ID: invalid }, projectRoot: controlledRoot }), /native-service-signing-team-invalid/)
    }
})
