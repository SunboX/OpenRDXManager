import assert from 'node:assert/strict'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import test from 'node:test'

import { buildNativeServiceForTest } from '../scripts/build-native-service.mjs'

/**
 * Creates the minimal locked Cargo project accepted by the native build hook.
 * @param {string} root - Empty temporary project root.
 * @returns {Promise<void>} Resolves after writing the manifest, lock, and binary source.
 */
async function createMinimalNativeProject(root) {
    const crateRoot = join(root, 'native', 'rdx-service')
    await mkdir(join(crateRoot, 'src', 'bin'), { recursive: true })
    await writeFile(join(crateRoot, 'Cargo.toml'), '[package]\nname = "rdx-service"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n\n[[bin]]\nname = "openrdx-hardware"\npath = "src/bin/openrdx-hardware.rs"\n')
    await writeFile(join(crateRoot, 'Cargo.lock'), '# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "rdx-service"\nversion = "0.1.0"\n')
    await writeFile(join(crateRoot, 'src', 'bin', 'openrdx-hardware.rs'), 'fn main() {}\n')
}

test('macOS native builds disable chained fixups before Cargo runs', async (context) => {
    const temporaryDirectory = await mkdtemp(join(tmpdir(), 'openrdx-native-macos-linker-'))
    context.after(() => rm(temporaryDirectory, { force: true, recursive: true }))
    const projectRoot = join(temporaryDirectory, 'project')
    const runtimeRoot = join(temporaryDirectory, 'runtime')
    await createMinimalNativeProject(projectRoot)
    await mkdir(runtimeRoot)
    let observedEnvironment = null

    await buildNativeServiceForTest(
        {
            environment: {
                CARGO_ENCODED_RUSTFLAGS: 'ambient-encoded-flags',
                KEEP_ME: 'preserved',
                PATH: '/usr/bin:/bin',
                RUSTFLAGS: 'ambient-rustflags'
            },
            platform: 'darwin',
            projectRoot,
            testRuntimeRoot: runtimeRoot
        },
        {
            runCargo: async ({ environment, paths }) => {
                observedEnvironment = environment
                const artifactPath = join(paths.targetDirectory, 'debug', paths.executableName)
                await mkdir(dirname(artifactPath), { recursive: true })
                await writeFile(artifactPath, 'native-artifact')
                return { stdout: `${JSON.stringify({ reason: 'compiler-artifact', target: { name: 'openrdx-hardware', kind: ['bin'] }, profile: { test: false }, executable: artifactPath })}\n` }
            }
        }
    )

    assert.equal(observedEnvironment?.KEEP_ME, 'preserved')
    assert.equal(observedEnvironment?.CARGO_ENCODED_RUSTFLAGS, '-Clink-arg=-Wl,-no_fixup_chains')
    assert.equal(Object.hasOwn(observedEnvironment ?? {}, 'RUSTFLAGS'), false)
})
