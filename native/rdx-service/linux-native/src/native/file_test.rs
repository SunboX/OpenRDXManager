//! Closed mounted-volume write/read test operations.

use std::ffi::CString;

use super::*;

impl NativeVolumeLeases {
    /// Performs closed exact mounted-volume file I/O relative to one retained directory fd.
    pub(crate) fn write_read_file(&mut self, filename: &str, bytes: &[u8]) -> FileTestOutcome {
        if self._mount_fds.len() != 1
            || bytes.is_empty()
            || bytes.len() > 4 * 1024 * 1024
            || !valid_test_filename(filename)
        {
            return FileTestOutcome {
                operation: Err(NativeError::InvalidRequest),
                operation_certainty: HostOperationOutcome::NotAttempted(
                    NativeError::InvalidRequest,
                ),
                cleanup: HostOperationOutcome::NotAttempted(NativeError::InvalidRequest),
            };
        }
        let filename = match CString::new(filename) {
            Ok(filename) => filename,
            Err(_) => {
                return FileTestOutcome {
                    operation: Err(NativeError::InvalidRequest),
                    operation_certainty: HostOperationOutcome::NotAttempted(
                        NativeError::InvalidRequest,
                    ),
                    cleanup: HostOperationOutcome::NotAttempted(NativeError::InvalidRequest),
                };
            }
        };
        let directory = self._mount_fds[0].directory.copied();
        let (operation, operation_certainty, created) =
            write_close_reopen_read(directory, &filename, bytes);
        // SAFETY: directory is the retained exact mount descriptor and filename
        // is an app-generated single basename with no separators. A failed
        // create-new call cannot leave an app-owned file requiring cleanup.
        let cleanup = if !created {
            HostOperationOutcome::Succeeded
        } else if unsafe { libc::unlinkat(directory, filename.as_ptr(), 0) } == 0 {
            // SAFETY: directory is the retained exact mount and fsync has no pointers.
            if unsafe { libc::fsync(directory) } == 0 {
                HostOperationOutcome::Succeeded
            } else {
                HostOperationOutcome::CompletionUnknown(last_native_error())
            }
        } else {
            HostOperationOutcome::CompletionUnknown(last_native_error())
        };
        FileTestOutcome {
            operation,
            operation_certainty,
            cleanup,
        }
    }
}

/// Accepts only the app-owned random basename generated by the parent service.
fn valid_test_filename(filename: &str) -> bool {
    let prefix = ".openrdx-write-read-";
    let suffix = ".tmp";
    filename.len() == prefix.len() + 32 + suffix.len()
        && filename.starts_with(prefix)
        && filename.ends_with(suffix)
        && filename[prefix.len()..filename.len() - suffix.len()]
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
}

/// Creates, writes, flushes, closes, reopens, and reads one exact relative file.
fn write_close_reopen_read(
    directory: libc::c_int,
    filename: &CString,
    bytes: &[u8],
) -> (Result<Vec<u8>, NativeError>, HostOperationOutcome, bool) {
    // SAFETY: directory is retained, filename is one validated basename, and
    // flags forbid replacement and symlink traversal.
    let raw = unsafe {
        libc::openat(
            directory,
            filename.as_ptr(),
            libc::O_CREAT | libc::O_EXCL | libc::O_NOFOLLOW | libc::O_CLOEXEC | libc::O_WRONLY,
            0o600,
        )
    };
    if raw < 0 {
        let error = last_native_error();
        return (
            Err(error),
            HostOperationOutcome::CompletionUnknown(error),
            false,
        );
    }
    let file = OwnedFd::new(raw);
    if let Err(error) = write_all_fd(file.copied(), bytes) {
        return (
            Err(error),
            HostOperationOutcome::CompletionUnknown(error),
            true,
        );
    }
    // SAFETY: file owns a live descriptor and fsync has no pointer arguments.
    if unsafe { libc::fsync(file.copied()) } != 0 {
        let error = last_native_error();
        return (
            Err(error),
            HostOperationOutcome::CompletionUnknown(error),
            true,
        );
    }
    drop(file);
    // SAFETY: same retained directory and exact no-follow basename; create is omitted.
    let raw = unsafe {
        libc::openat(
            directory,
            filename.as_ptr(),
            libc::O_NOFOLLOW | libc::O_CLOEXEC | libc::O_RDONLY,
        )
    };
    if raw < 0 {
        let error = last_native_error();
        return (
            Err(error),
            HostOperationOutcome::CompletionUnknown(error),
            true,
        );
    }
    let file = OwnedFd::new(raw);
    let operation = read_exact_fd(file.copied(), bytes.len());
    let certainty = operation.as_ref().map_or_else(
        |error| HostOperationOutcome::CompletionUnknown(*error),
        |_| HostOperationOutcome::Succeeded,
    );
    (operation, certainty, true)
}

/// Writes every byte, retrying only EINTR and accepting partial progress.
fn write_all_fd(fd: libc::c_int, mut bytes: &[u8]) -> Result<(), NativeError> {
    while !bytes.is_empty() {
        // SAFETY: bytes points to initialized memory for its bounded length.
        let written = unsafe { libc::write(fd, bytes.as_ptr().cast(), bytes.len()) };
        if written > 0 {
            bytes = &bytes[written as usize..];
        } else if written < 0 && last_native_error() == NativeError::Interrupted {
            continue;
        } else {
            return Err(last_native_error());
        }
    }
    Ok(())
}

/// Reads the exact expected length and rejects trailing bytes.
fn read_exact_fd(fd: libc::c_int, length: usize) -> Result<Vec<u8>, NativeError> {
    let mut output = vec![0_u8; length];
    let mut offset = 0;
    while offset < length {
        // SAFETY: the suffix is writable for its exact remaining length.
        let read = unsafe { libc::read(fd, output[offset..].as_mut_ptr().cast(), length - offset) };
        if read > 0 {
            offset += read as usize;
        } else if read < 0 && last_native_error() == NativeError::Interrupted {
            continue;
        } else {
            return Err(last_native_error());
        }
    }
    let mut trailing = [0_u8; 1];
    // SAFETY: trailing is valid writable storage for one byte.
    let read = unsafe { libc::read(fd, trailing.as_mut_ptr().cast(), 1) };
    if read != 0 {
        return Err(if read < 0 {
            last_native_error()
        } else {
            NativeError::Other
        });
    }
    Ok(output)
}
